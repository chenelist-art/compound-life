/* Builds the game's data from the files you edit:
     events/*.json      every decision (rules and text in English, Simplified and Traditional Chinese)
     events/_shared.json  option sets several events use ("use") and shared consequences
     events/_names.json   given names for the people in a life, by country, in the three languages
     i18n/<lang>.json   the rest of the game's text, one file per language
   into the files the pages load:
     gen/events.js      every event's rules, without text
     gen/en.js, gen/zh.js, gen/zht.js   all the text for one language; a page loads only the one in use
   Everything is checked first (tools/validate.js, with a short simulation); if anything is wrong nothing is written.
   node tools/build.js            check, then write gen/
   node tools/build.js --quick    skip the simulation (faster while editing) */
const fs=require('fs'),path=require('path');
const ROOT=path.join(__dirname,'..');
const LANGS=['en','zh','zht'];
/* the order events are dealt in when two are due the same year: country cards first, then these themes, then any other file */
const THEMES=['childhood','career','money','home','family','people','health','later-life'];

function readJSON(f){const txt=fs.readFileSync(f,'utf8');try{return JSON.parse(txt)}catch(e){const m=/position (\d+)/.exec(e.message);let where='';
  if(m){const p=+m[1],before=txt.slice(0,p),line=before.split('\n').length,col=p-before.lastIndexOf('\n');where=' (line '+line+', column '+col+')'}
  const err=new Error(path.relative(ROOT,f)+': not valid JSON'+where+': '+e.message);err.file=f;throw err}}
function fileOrder(a,b){const ka=key(a),kb=key(b);return ka<kb?-1:ka>kb?1:0;function key(f){const n=f.replace(/\.json$/,'');if(n.startsWith('country-'))return '0'+n;const i=THEMES.indexOf(n);return i>=0?'1'+String(i).padStart(3,'0'):'2'+n}}

/* everything the build needs, read from disk */
function load(root){root=root||ROOT;const dir=path.join(root,'events');
 const files=fs.readdirSync(dir).filter(f=>f.endsWith('.json')&&!f.startsWith('_')).sort(fileOrder);
 const shared=fs.existsSync(path.join(dir,'_shared.json'))?readJSON(path.join(dir,'_shared.json')):{};
 const events=[],byFile={};
 for(const f of files){const d=readJSON(path.join(dir,f));byFile[f]=d;
  for(const e of d.events||[])events.push(Object.assign({},e,d.country?{country:d.country}:{},{_file:'events/'+f}))}
 const ui={};for(const L of LANGS){const f=path.join(root,'i18n',L+'.json');ui[L]=fs.existsSync(f)?readJSON(f):{}}
 const nf=path.join(dir,'_names.json'),names=fs.existsSync(nf)?readJSON(nf).names||{}:{};
 return{root,files,byFile,events,templates:shared.templates||{},later:shared.later||{},ui,names}}

/* an event's text keys: ".x" belongs to the event (e.<id>.x); other keys are kept as they are */
const full=(pre,k)=>k[0]==='.'?pre+k:k;
function texts(data){const dict={};for(const L of LANGS)dict[L]=Object.assign({},data.ui[L]);
 for(const[name,t]of Object.entries(data.templates))for(const L of LANGS)for(const[k,v]of Object.entries(t.i18n&&t.i18n[L]||{}))dict[L][full('e.'+t.key,k)]=v;
 for(const e of data.events){for(const L of LANGS)for(const[k,v]of Object.entries(e.i18n&&e.i18n[L]||{}))dict[L][full('e.'+e.id,k)]=v;
  if(e.tarot&&typeof e.tarot==='object')for(const L of LANGS)dict[L]['tn.'+e.id]=e.tarot[L]}
 /* names of the people in a life: nm.<country>.<f|m>.<n> */
 for(const[c,bySex]of Object.entries(data.names||{}))for(const[sex,list]of Object.entries(bySex))list.forEach((x,i)=>LANGS.forEach((L,j)=>{dict[L]['nm.'+c+'.'+sex+'.'+i]=x[j]}));
 /* a tarot name can be borrowed from another card: "tarot": "lend" */
 for(const e of data.events)if(typeof e.tarot==='string')for(const L of LANGS)dict[L]['tn.'+e.id]=dict[L]['tn.'+e.tarot];
 return dict}
/* an event's rules: everything but its text and notes */
const DROP=new Set(['i18n','src','about','_file']);
function rules(e){const o={};for(const k in e)if(!DROP.has(k))o[k]=k==='tarot'&&typeof e[k]==='object'?undefined:e[k];return o}
function generate(data){const out={};
 const head='/* generated by tools/build.js from events/*.json and i18n/*.json: do not edit (edit those and run node tools/build.js) */\n';
 const tpl={};for(const[n,t]of Object.entries(data.templates))tpl[n]=rules(t);
 /* how many names each list has (the engine picks by number; the names themselves are text) */
 const names={};for(const[c,bySex]of Object.entries(data.names||{})){names[c]={};for(const[sex,list]of Object.entries(bySex))names[c][sex]=list.length}
 out['gen/events.js']=head+'var EVDATA='+JSON.stringify({templates:tpl,later:data.later,names,events:data.events.map(rules)})+';\n';
 const dict=texts(data);
 for(const L of LANGS)out['gen/'+L+'.js']=head+'I18N.add('+JSON.stringify(L)+','+JSON.stringify(dict[L])+');\n';
 return out}
function write(out,root){root=root||ROOT;fs.mkdirSync(path.join(root,'gen'),{recursive:true});for(const[f,txt]of Object.entries(out))fs.writeFileSync(path.join(root,f),txt)}

module.exports={load,generate,texts,write,readJSON,LANGS,THEMES,ROOT,full};

if(require.main===module){
 const quick=process.argv.includes('--quick');
 let data;try{data=load()}catch(e){console.error(e.message);process.exit(1)}
 const{check}=require('./validate.js');
 const r=check(data,{sim:quick?0:60,stale:false});
 if(r.errors.length){console.error('\nNothing was written: fix the '+r.errors.length+' problem'+(r.errors.length>1?'s':'')+' above first.');process.exit(1)}
 const out=generate(data);write(out);
 const kb=f=>(Buffer.byteLength(out[f])/1024).toFixed(0)+' KB';
 console.log('Built '+data.events.length+' events: gen/events.js '+kb('gen/events.js')+', '+LANGS.map(L=>'gen/'+L+'.js '+kb('gen/'+L+'.js')).join(', '));
}
